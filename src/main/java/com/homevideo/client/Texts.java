package com.homevideo.client;

import java.util.ArrayList;
import java.util.List;
import java.util.Locale;

public final class Texts {
	private Texts() {}

	public static List<String> get(int idx, int loop, String name) {
		String N = name.toUpperCase(Locale.ROOT);
		String E = loop > 0 ? N : "ЭДГАР";
		List<String> t = new ArrayList<>();
		switch (idx) {
			case 1 -> {
				t.add("[ПЛЁНКА №1. ДОМАШНЯЯ ЗАПИСЬ. ЗВУК ЕСТЬ.]");
				t.add("[ТАЙМКОД: 31 ОКТ 1994, 22:47]");
				t.add("{E}: ...Идёт? Красная точка горит. Идёт.");
				t.add("{E}: Привет. Это наш новый дом. Лес, тишина, ни одного соседа на двадцать километров. Мира, не прячься, улыбнись в камеру.");
				t.add("[ГОЛОС ЗА КАДРОМ — АННА: «Эдгар, ужин остывает».]");
				t.add("МИРА: Папа, там кто-то стоит.");
				t.add("{E}: Где, солнышко?");
				t.add("МИРА: В углу. Он не любит, когда на него смотрят.");
				t.add("{E}: Там никого нет, это тень от шкафа.");
				t.add("[ШУМ]");
				t.add("[В ДВЕРНОМ ПРОЁМЕ ЗА СПИНОЙ {E} СТОИТ ВЫСОКАЯ ФИГУРА. {E} НЕ ОБОРАЧИВАЕТСЯ.]");
				t.add("{E}: Завтра сходим за грибами.");
				t.add("[ЗАПИСЬ ОБРЫВАЕТСЯ]");
				if (loop > 0) t.add("[НА ПОЛЯХ КТО-ТО ЦАРАПАЛ ГВОЗДЁМ: «{N}, ТЫ УЖЕ ЭТО СМОТРЕЛ»]");
			}
			case 2 -> {
				t.add("[ПЛЁНКА №2. 2 НОЯБРЯ 1994.]");
				t.add("{E}: Я больше не выпускаю камеру из рук. Хочу, чтобы вы знали почему.");
				t.add("{E}: Оно не двигается, пока я на него смотрю. Просто стоит. Но стоит мне моргнуть или отвернуться, оно оказывается ближе.");
				t.add("{E}: Мира говорит: «Пока красная точка горит, он стоит смирно». Она права. Я проверил. Двенадцать раз.");
				t.add("МИРА: Папа, он сегодня стоял у окна. Потом у кровати. Потом у меня за спиной.");
				t.add("{E}: Не отводи взгляд. Слышишь? Не отводи взгляд.");
				t.add("[ШУМ]");
				t.add("{E}: Правило первое: смотри на него. Правило второе: не подпускай близко. Правило третье: он не любит, когда на него смотрят слишком долго. Тогда он уходит. Но возвращается за спиной.");
				t.add("[ТАЙМКОД ЗАСТРЕВАЕТ: 03:14 / 03:14 / 03:14]");
				if (loop > 0) t.add("[В КАДРЕ МЕЛЬКАЕТ КАЛЕНДАРЬ. НА НЁМ {L} РАЗ ОБВЕДЕНО 31 ОКТЯБРЯ.]");
			}
			case 3 -> {
				t.add("[ПЛЁНКА №3. 5 НОЯБРЯ 1994. ИЗОБРАЖЕНИЕ ДРОЖИТ.]");
				t.add("{E}: Миры нет с вечера. Кровать застелена. Дверь изнутри на засове.");
				t.add("{E}: Я пишу её имя на ладони. МИРА. МИРА. Чтобы не забыть.");
				t.add("{E}: Я пересмотрел плёнку номер один. Кадр за кадром. В ней слышен женский голос. Анна. Она зовёт меня ужинать.");
				t.add("{E}: Я не знаю никакой Анны.");
				t.add("[ДОЛГАЯ ТИШИНА]");
				t.add("{E}: В коридоре висит фотография. Женщина, девочка и я. Лицо женщины... не получается вспомнить. Как будто его вырезали.");
				t.add("{E}: Оно не убивает. Оно стирает. Сначала лица. Потом имена. Потом тех, кто помнит.");
				t.add("[КАМЕРА ПАДАЕТ. В КАДРЕ ПОТОЛОК. ЗА КАДРОМ ШАГИ. ОНИ ОСТАНАВЛИВАЮТСЯ.]");
				if (loop > 0) t.add("[НА ТУМБОЧКЕ ЛЕЖАТ ТВОИ ЧАСЫ. ТЫ НЕ ПОМНИШЬ, КОГДА ИХ СНЯЛ.]");
			}
			case 4 -> {
				t.add("[ПЛЁНКА №4. ДАТЫ НЕТ. ТАЙМКОД: --:--:--]");
				t.add("{E}: Я понял, на что смотрю. Оно живёт не в доме. Оно живёт в плёнке.");
				t.add("{E}: Каждый раз, когда кто-то нажимает PLAY, оно идёт к тому, кто в кадре.");
				t.add("{E}: Я пытался записать поверх. Новая запись стёрла старую: Анну, Миру, даже мои первые слова. Остался только я. И то, что смотрит.");
				t.add("{E}: Но я до сих пор помню, как зовут дочь. Значит, перезапись идёт не до конца.");
				t.add("{E}: Оно не хочет убить, слышишь? Оно хочет, чтобы на него посмотрели в ответ. Один раз. По-настоящему.");
				t.add("{E}: Если ты смотришь это... ты тоже в кадре. Тебя тоже записали поверх. Тебя тоже кто-то стёр.");
				t.add("[ЗА СПИНОЙ СТОИТ ФИГУРА. НА ЛИЦЕ ПОМЕХИ.]");
				t.add("[НА ОДИН КАДР ПОМЕХИ ИСЧЕЗАЮТ. ЛИЦО ПОХОЖЕ НА ТВОЁ.]");
				t.add("[ЗАПИСЬ ОБРЫВАЕТСЯ]");
				if (loop > 0) t.add("[НА СТЕНЕ ЗА СПИНОЙ {L} ЦАРАПИН. ПО ОДНОЙ НА КАЖДОГО.]");
			}
			case 5 -> {
				t.add("[ПЛЁНКА №5. НА КОРПУСЕ ФЛОМАСТЕРОМ: «{N}. СЕГОДНЯ.»]");
				t.add("[ЭТА ПЛЁНКА ЗАПИСЫВАЕТСЯ ПРЯМО СЕЙЧАС.]");
				t.add("ГОЛОС: Ты дошёл до пятой кассеты. Молодец.");
				t.add("ГОЛОС: Эдгар не был последним. Эдгар был предпоследним.");
				t.add("ГОЛОС: Дом всегда один и тот же. Лес один и тот же. Кассета одна и та же. Меняется только тот, кого записывают поверх.");
				t.add("ГОЛОС: Все, кто был здесь до тебя, никуда не делись. Они стоят в углах. Они смотрят, как ты идёшь. Они не злые. Они просто хотят, чтобы кто-нибудь посмотрел на них в ответ.");
				t.add("ГОЛОС: Но ты ведь не смотришь. Ты моргаешь.");
				t.add("ГОЛОС: Вернись домой, {N}. Нажми PLAY. Досмотри до конца.");
				t.add("[ЛЕНТА ЗАКАНЧИВАЕТСЯ]");
			}
			default -> {
				t.add("[PLAY]");
				t.add("[НА ЭКРАНЕ КОМНАТА. ТЫ СТОИШЬ В ЕЁ ЦЕНТРЕ. ТЫ СМОТРИШЬ В КАМЕРУ.]");
				t.add("[ЗА СПИНОЙ ЕЩЁ ОДИН {N}. ОН ТОЖЕ СМОТРИТ В КАМЕРУ.]");
				t.add("[ПОТОМ ЕЩЁ ОДИН. ПОТОМ ЕЩЁ.]");
				t.add("[ИХ СТО. ИХ ТЫСЯЧА. ВСЕ — {N}.]");
				t.add("ГОЛОС: Спасибо, что досмотрел.");
				t.add("ГОЛОС: Теперь твоя очередь стоять в углу.");
				t.add("ГОЛОС: Запись №{L} сохранена.");
				t.add("[REC]");
				t.add("[ПЕРЕЗАПИСЬ...]");
			}
		}
		List<String> out = new ArrayList<>();
		for (String s : t) {
			out.add(s.replace("{E}", E).replace("{N}", N).replace("{L}", String.valueOf(loop + 1)));
		}
		return out;
	}
}
